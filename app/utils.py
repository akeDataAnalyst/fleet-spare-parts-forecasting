import os
from pathlib import Path
import pandas as pd
import streamlit as st

# Resolve project root dynamically (one level above app/)
PROJECT_ROOT = Path(__file__).resolve().parent.parent
RAW_DIR = PROJECT_ROOT / "data" / "raw"
PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"


def configure_page(title: str, icon: str = "🚛") -> None:
    """Applies consistent page config and sidebar branding across all pages."""
    st.set_page_config(
        page_title=f"{title} | Fleet Spare-Parts Forecasting",
        page_icon=icon,
        layout="wide",
        initial_sidebar_state="expanded",
    )


def render_sidebar_footer() -> None:
    """Renders consistent developer credit and scope note in the sidebar."""
    st.sidebar.markdown("---")
    st.sidebar.markdown(
        "**Scope:** Demand Forecasting & Maintenance Trend Diagnostics (36-Month Horizon: 2023–2025)"
    )
    st.sidebar.caption("Developed by Aklilu Abera Dana | Supply Chain Data Analyst")


@st.cache_data
def load_processed_datasets() -> dict[str, pd.DataFrame]:
    """Loads all processed CSV tables generated by the analytics pipeline."""
    required_files = {
        "monthly_part": PROCESSED_DIR / "monthly_part_demand.csv",
        "monthly_vehicle": PROCESSED_DIR / "monthly_vehicle_demand.csv",
        "classification": PROCESSED_DIR / "part_demand_classification.csv",
        "model_comparison": PROCESSED_DIR / "model_comparison.csv",
        "forecasts": PROCESSED_DIR / "part_forecasts.csv",
        "risk_summary": PROCESSED_DIR / "part_risk_summary.csv",
    }

    missing = [str(p) for p in required_files.values() if not p.exists()]
    if missing:
        st.error(
            "Processed data files not found. Please run `notebooks/02_eda_and_classification.ipynb` "
            "and `notebooks/03_forecasting_and_risk.ipynb` first.\n\nMissing:\n"
            + "\n".join(f"- `{m}`" for m in missing)
        )
        st.stop()

    data = {
        "monthly_part": pd.read_csv(required_files["monthly_part"], parse_dates=["month"]),
        "monthly_vehicle": pd.read_csv(required_files["monthly_vehicle"], parse_dates=["month"]),
        "classification": pd.read_csv(required_files["classification"]),
        "model_comparison": pd.read_csv(required_files["model_comparison"]),
        "forecasts": pd.read_csv(required_files["forecasts"], parse_dates=["month"]),
        "risk_summary": pd.read_csv(required_files["risk_summary"]),
    }
    return data


@st.cache_data
def load_raw_datasets() -> dict[str, pd.DataFrame]:
    """Loads raw fleet, parts, and work-order tables when needed for granular drilldowns."""
    return {
        "fleet": pd.read_csv(RAW_DIR / "fleet_master.csv"),
        "parts": pd.read_csv(RAW_DIR / "parts_master.csv"),
        "work_orders": pd.read_csv(
            RAW_DIR / "maintenance_work_orders.csv", parse_dates=["work_order_date"]
        ),
    }